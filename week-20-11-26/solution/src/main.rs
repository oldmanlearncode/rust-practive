use rust_week_20_11_26::*;
use std::collections::HashMap;

fn main() {
    assert_eq!(longest_title(&[]), None);
    let titles = vec!["abcd".to_string(), "🦀🦀".to_string()];
    assert_eq!(longest_title(&titles), Some("abcd"));
    assert_eq!(longest_title(&["A".to_string(), "B".to_string()]), Some("A"));
    assert_eq!(longest_title(&[String::new(), String::new()]), Some(""));
    assert_eq!(longest_title(&["e\u{301}".to_string(), "A".to_string()]), Some("e\u{301}"));
    assert_eq!(join_titles(&[]), "");
    assert_eq!(join_titles(&[String::new()]), "");
    assert_eq!(join_titles(&[String::new(), String::new()]), "\n");
    let labels = vec![" A🦀 ".to_string(), String::new(), "B".to_string()];
    let before = labels.clone(); // Snapshot harness, không cho phép clone trong rename.
    assert_eq!(join_titles(&labels), " A🦀 \n\nB");
    assert_eq!(labels, before);

    let mut map = HashMap::new();
    map.insert("A".to_string(), "body".to_string());
    map.insert("B".to_string(), "other".to_string());
    let before = map.clone();
    assert!(matches!(rename_page(&mut map, "missing", " ".to_string()), Err(RenameError::BlankName)));
    assert_eq!(map, before);
    assert!(matches!(rename_page(&mut map, "missing", "B".to_string()), Err(RenameError::Missing)));
    assert_eq!(map, before);
    assert!(matches!(rename_page(&mut map, "A", "B".to_string()), Err(RenameError::Conflict)));
    assert_eq!(map, before);
    assert!(rename_page(&mut map, "A", "A".to_string()).is_ok());
    assert_eq!(map, before);
    assert!(rename_page(&mut map, "A", " Trang 🦀 ".to_string()).is_ok());
    assert_eq!(map.len(), 2);
    assert!(!map.contains_key("A"));
    assert_eq!(map.get(" Trang 🦀 "), Some(&"body".to_string()));
    assert_eq!(map.get("B"), Some(&"other".to_string()));

    let mut wiki = WikiNotes::new();
    assert_eq!(wiki.len(), 0);
    assert!(wiki.body("A").is_none());
    assert!(wiki.search("Rust").is_empty());
    assert!(wiki.length_counts().is_empty());
    assert!(matches!(wiki.create(" \n".to_string(), "x".to_string()), Err(RenameError::BlankName)));
    assert_eq!(wiki.len(), 0);
    assert!(wiki.create("A".to_string(), "Rust ownership 🦀".to_string()).is_ok());
    assert!(wiki.create("🦀".to_string(), "Rust".to_string()).is_ok());
    assert!(wiki.create(" A ".to_string(), String::new()).is_ok());
    assert!(wiki.create("Rust".to_string(), "unrelated".to_string()).is_ok());
    assert_eq!(wiki.len(), 4);
    let snapshot = wiki.search(" Rust ");
    assert_eq!(snapshot.len(), 2);
    assert!(snapshot.contains(&"A".to_string()));
    assert!(snapshot.contains(&"🦀".to_string()));
    assert!(wiki.search("rust").is_empty());
    assert!(wiki.search(" \n").is_empty());
    let counts = wiki.length_counts();
    assert_eq!(counts.len(), 3);
    assert_eq!(counts.get(&1), Some(&2));
    assert_eq!(counts.get(&3), Some(&1));
    assert_eq!(counts.get(&4), Some(&1));
    assert!(matches!(wiki.create("A".to_string(), "replace".to_string()), Err(RenameError::Conflict)));
    assert!(matches!(wiki.rename("A", "🦀".to_string()), Err(RenameError::Conflict)));
    assert!(matches!(wiki.rename("A", String::new()), Err(RenameError::BlankName)));
    assert!(matches!(wiki.rename("missing", "B".to_string()), Err(RenameError::Missing)));
    assert_eq!(wiki.len(), 4);
    assert_eq!(wiki.body("A"), Some("Rust ownership 🦀"));
    assert_eq!(wiki.body("🦀"), Some("Rust"));
    assert_eq!(wiki.body(" A "), Some(""));
    assert_eq!(wiki.body("Rust"), Some("unrelated"));
    assert_eq!(wiki.length_counts(), counts);
    assert!(wiki.rename("A", "A".to_string()).is_ok());
    assert!(wiki.rename("A", "Trang mới".to_string()).is_ok());
    assert_eq!(wiki.len(), 4);
    assert!(wiki.body("A").is_none());
    assert_eq!(wiki.body("Trang mới"), Some("Rust ownership 🦀"));
    let now = wiki.search("Rust");
    assert_eq!(now.len(), 2);
    assert!(now.contains(&"Trang mới".to_string()));
    assert!(now.contains(&"🦀".to_string()));
    assert!(snapshot.contains(&"A".to_string()));
    assert!(!snapshot.contains(&"Trang mới".to_string()));
    assert_eq!(counts.get(&1), Some(&2));
    assert_eq!(wiki.length_counts().get(&1), Some(&1));
    assert_eq!(wiki.length_counts().get(&9), Some(&1));
    println!("Tất cả case đã pass — có thể nộp review.");
}
